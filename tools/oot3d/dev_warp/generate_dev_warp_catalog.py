#!/usr/bin/env python3
"""Generates the developer warp catalog from Ship of Harkinian's debug warp screen.

The F1 developer warp menu mirrors Ship of Harkinian's Debug Warp Screen: its
vanilla scene list (`sScenes`), its "Better Debug Warp Screen" list with
entrances per scene (`sBetterScenes`) and its grotto table (`sBetterGrottos`),
all in `soh/src/overlays/gamestates/ovl_select/z_select.c`. Entrance and scene
constants are resolved through SoH's `entrance_table.h` and `scene_table.h`.

Each entrance carries the scene and spawn SoH expects; the runtime checks them
against the title's own global entrance table in code.bin before offering it,
so a list entry that OOT3D does not have is shown disabled, never guessed.
Only the English, German and French names are kept (the F1 font has no
Japanese glyphs).

usage: generate_dev_warp_catalog.py <soh root> <output .inc>
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

SELECT = "src/overlays/gamestates/ovl_select/z_select.c"
ENTRANCES = "include/tables/entrance_table.h"
SCENES = "include/tables/scene_table.h"

TOKEN = re.compile(
    r'\s+|//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|[A-Za-z_][A-Za-z0-9_]*|'
    r"-?(?:0[xX][0-9A-Fa-f]+|\d+\.\d*f?|\d+)|[{},]|.",
    re.S)


def tokens(text: str) -> list[str]:
    result = []
    position = 0
    while position < len(text):
        match = TOKEN.match(text, position)
        if match is None:
            raise ValueError(f"unexpected character {text[position]!r} at {position}")
        value = match.group(0)
        position = match.end()
        if value.isspace() or value.startswith("//") or value.startswith("/*"):
            continue
        result.append(value)
    return result


def parse_braces(items: list[str], index: int):
    """Parses `{ field, field, ... }` starting at items[index] == '{'."""
    assert items[index] == "{"
    index += 1
    fields = []
    current: list = []
    while True:
        token = items[index]
        if token == "{":
            nested, index = parse_braces(items, index)
            current.append(nested)
            continue
        if token in (",", "}"):
            if current:
                fields.append(current)
            current = []
            index += 1
            if token == "}":
                return fields, index
            continue
        current.append(token)
        index += 1


def table(text: str, name: str):
    start = text.index(name + "[] = {")
    items = tokens(text[start + len(name) + len("[] = "):])
    fields, _ = parse_braces(items, 0)
    # Each row is one braced initializer.
    return [field[0] for field in fields]


def string(field: list) -> str:
    parts = [part for part in field if isinstance(part, str) and part.startswith('"')]
    if not parts:
        raise ValueError(f"field has no string: {field}")
    return "".join(bytes(part[1:-1], "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")
                   for part in parts)


def scalar(field: list) -> str:
    if len(field) != 1 or not isinstance(field[0], str):
        raise ValueError(f"expected one value: {field}")
    return field[0]


def entrance_table(text: str) -> dict[str, tuple[int, str, int]]:
    result = {}
    index = 0
    for match in re.finditer(r"DEFINE_ENTRANCE\(\s*(\w+)\s*,\s*(\w+)\s*,\s*(\d+)", text):
        result[match.group(1)] = (index, match.group(2), int(match.group(3)))
        index += 1
    return result


def scene_table(text: str) -> dict[str, int]:
    return {match.group(1): index
            for index, match in enumerate(re.finditer(r"DEFINE_SCENE\(\s*\w+\s*,\s*\w+\s*,\s*(\w+)", text))}


def cxx(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    root = Path(sys.argv[1])
    output = Path(sys.argv[2])
    sources = {name: (root / name).read_bytes() for name in (SELECT, ENTRANCES, SCENES)}
    select = sources[SELECT].decode("utf-8")
    entrances = entrance_table(sources[ENTRANCES].decode("utf-8"))
    scenes = scene_table(sources[SCENES].decode("utf-8"))

    def resolve_entrance(name: str) -> tuple[int, int, int]:
        index, scene, spawn = entrances[name]
        return index, scenes[scene], spawn

    lines = []
    emit = lines.append
    emit("// Generated by tools/oot3d/dev_warp/generate_dev_warp_catalog.py; do not edit.")
    emit("// Source: Ship of Harkinian's Debug Warp Screen (sScenes, sBetterScenes,")
    emit("// sBetterGrottos) with its entrance and scene tables:")
    for name, data in sources.items():
        emit(f"//   soh/{name} sha256 {hashlib.sha256(data).hexdigest()}")
    emit("// Each entrance names the scene and spawn SoH expects; the runtime checks")
    emit("// them against OOT3D's code.bin entrance table before offering it.")
    emit("")

    # Vanilla list: one entrance per scene; the title-screen entry has no entrance.
    emit("inline constexpr DevWarpEntrance kDevWarpVanillaEntrances[] = {")
    vanilla_scenes = []
    for entry in table(select, "sScenes"):
        load = scalar(entry[4])
        names = [string(entry[column]) for column in (1, 2, 3)]
        if load != "Select_LoadGame":
            continue
        index, scene, spawn = resolve_entrance(scalar(entry[5]))
        vanilla_scenes.append(names)
        emit(f"    {{{cxx(names[0])}, {cxx(names[1])}, {cxx(names[2])}, 0x{index:04X}, {scene}, {spawn}, -1}},")
    emit("};")
    emit("")

    emit("inline constexpr DevWarpEntrance kDevWarpBetterEntrances[] = {")
    better_scenes = []
    entrance_count = 0
    for entry in table(select, "sBetterScenes"):
        names = [string(entry[column]) for column in (1, 2, 3)]
        load = scalar(entry[4])
        count = int(scalar(entry[5]), 0)
        pairs = [pair[0] for pair in entry[6][0]]
        if len(pairs) != count:
            raise ValueError(f"{names[0]}: {len(pairs)} entrances, declared {count}")
        grotto = load == "Select_Grotto_LoadGame"
        better_scenes.append((names, entrance_count, count, grotto))
        for pair in pairs:
            pair_names = [string(pair[column]) for column in (1, 2, 3)]
            value = scalar(pair[4])
            if grotto:
                emit(f"    {{{cxx(pair_names[0])}, {cxx(pair_names[1])}, {cxx(pair_names[2])}, 0, 0, 0, {int(value, 0)}}},")
            else:
                index, scene, spawn = resolve_entrance(value)
                emit(f"    {{{cxx(pair_names[0])}, {cxx(pair_names[1])}, {cxx(pair_names[2])}, "
                     f"0x{index:04X}, {scene}, {spawn}, -1}},")
            entrance_count += 1
    emit("};")
    emit("")

    emit("inline constexpr DevWarpScene kDevWarpBetterScenes[] = {")
    for names, first, count, grotto in better_scenes:
        emit(f"    {{{cxx(names[0])}, {cxx(names[1])}, {cxx(names[2])}, {first}, {count}, "
             f"{'true' if grotto else 'false'}}},")
    emit("};")
    emit("")

    emit("inline constexpr DevWarpGrotto kDevWarpGrottos[] = {")
    for entry in table(select, "sBetterGrottos"):
        index, scene, spawn = resolve_entrance(scalar(entry[0]))
        back, back_scene, back_spawn = resolve_entrance(scalar(entry[1]))
        room = int(scalar(entry[2]), 0)
        data = int(scalar(entry[3]), 0)
        exit_scene = scenes[scalar(entry[4])]
        x, y, z = (float(scalar(value).rstrip("f")) for value in entry[5][0])
        emit(f"    {{0x{index:04X}, {scene}, {spawn}, 0x{back:04X}, {back_scene}, {back_spawn}, {room}, "
             f"0x{data & 0xFF:02X}, {exit_scene}, {{{x:.1f}F, {y:.1f}F, {z:.1f}F}}}},")
    emit("};")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(vanilla_scenes)} vanilla scenes, {len(better_scenes)} better scenes, "
          f"{entrance_count} better entrances -> {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
