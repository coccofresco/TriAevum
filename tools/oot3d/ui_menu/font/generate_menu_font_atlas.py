"""Bakes the in-game menu font atlases into a C++ source.

The menu is drawn by the native UI renderer from glyph quads, so the fonts are
rasterized once here (Pillow / FreeType) into alpha atlases: Fira Sans
Condensed Regular (body text) and Bold (keys, tabs, headings), SIL Open Font
License 1.1 (see OFL.txt beside the fonts). Each atlas is stored as a PNG
(8-bit grayscale coverage) with its glyph table, and decoded at run time.

    python generate_menu_font_atlas.py [--out ../oot3d_menu_font_atlas_data.cpp]

Pillow is the only dependency. The output is deterministic for a given Pillow
and FreeType build and is checked in; regenerate it after changing the fonts,
the glyph set or the pixel size.
"""

from __future__ import annotations

import argparse
import io
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
STYLES = (
    ("body", "FiraSansCondensed-Regular.ttf"),
    ("heading", "FiraSansCondensed-Bold.ttf"),
)
# Glyph height in atlas pixels. A 1080p window shows the largest menu text at
# about 48 px and 4K at about 96 px, so 72 px keeps text crisp up to 1440p and
# only mildly magnified at 4K.
PIXEL_SIZE = 72
PADDING = 2
ATLAS_WIDTH = 1024


def glyph_set() -> list[int]:
    # ASCII, Latin-1, the dashes, quotes, bullet, ellipsis, single guillemets
    # (the menu's arrows) and the four arrows. Fira Sans has no geometric
    # triangles or check mark; a code point it lacks is skipped (see bake).
    codes = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
    codes += [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026,
              0x2039, 0x203A, 0x2190, 0x2191, 0x2192, 0x2193]
    return codes


def render(font: ImageFont.FreeTypeFont, text: str):
    """The glyph's coverage bitmap with its baseline-left bearings and advance, or None."""
    bbox = font.getbbox(text, anchor="ls")  # baseline-left anchor
    advance = font.getlength(text)
    if bbox is None:
        return None
    left, top, right, bottom = bbox
    width = max(0, right - left)
    height = max(0, bottom - top)
    if width == 0 or height == 0:
        return None, left, top, advance
    image = Image.new("L", (width, height), 0)
    ImageDraw.Draw(image).text((-left, -top), text, font=font, fill=255, anchor="ls")
    return image, left, top, advance


def bake(style: str, file: str):
    font = ImageFont.truetype(str(HERE / file), PIXEL_SIZE)
    ascent, descent = font.getmetrics()
    glyphs = []
    x = PADDING
    y = PADDING
    row_height = 0
    # The .notdef box: what every code point the font lacks renders as.
    notdef = render(font, "￿")
    notdef_bytes = notdef[0].tobytes() if notdef and notdef[0] is not None else None
    # Pack glyph bitmaps left to right, row by row (simple shelf packing).
    cells = []
    for code in glyph_set():
        rendered = render(font, chr(code))
        if rendered is None:
            continue
        image, left, top, advance = rendered
        if image is None:
            glyphs.append((code, 0, 0, 0, 0, 0, 0, advance))
            continue
        # Skip glyphs the font does not cover (empty, or the .notdef box).
        if image.getbbox() is None and code != 0x20:
            continue
        if notdef_bytes is not None and image.tobytes() == notdef_bytes:
            print(f"{style}: U+{code:04X} is not in the font, skipped")
            continue
        cells.append((code, image, left, top, advance))
    atlas_height = 0
    placements = []
    for code, image, left, top, advance in cells:
        width, height = image.size
        if x + width + PADDING > ATLAS_WIDTH:
            x = PADDING
            y += row_height + PADDING
            row_height = 0
        placements.append((code, image, x, y, left, top, advance))
        x += width + PADDING
        row_height = max(row_height, height)
        atlas_height = max(atlas_height, y + height + PADDING)
    atlas_height = (atlas_height + 3) // 4 * 4
    atlas = Image.new("L", (ATLAS_WIDTH, atlas_height), 0)
    for code, image, ax, ay, left, top, advance in placements:
        atlas.paste(image, (ax, ay))
        glyphs.append((code, ax, ay, image.size[0], image.size[1], left, top, advance))
    glyphs.sort()
    png = io.BytesIO()
    atlas.save(png, format="PNG", optimize=True)
    return {
        "style": style,
        "png": png.getvalue(),
        "width": ATLAS_WIDTH,
        "height": atlas_height,
        "ascent": ascent,
        "descent": descent,
        "glyphs": glyphs,
    }


def emit(atlases, out: Path) -> None:
    lines = [
        "// Generated by tools/oot3d/ui_menu/font/generate_menu_font_atlas.py; do not edit.",
        "// Fira Sans Condensed (Mozilla Foundation, Telefonica S.A., bytes rasterized",
        "// at %d px), SIL Open Font License 1.1: LICENSES/FiraSans-OFL.txt." % PIXEL_SIZE,
        "#include \"oot3d_menu_font_atlas_data.h\"",
        "",
        "namespace Oot3dNativeGame::MenuFontData {",
        "namespace {",
    ]
    for atlas in atlases:
        name = atlas["style"]
        data = atlas["png"]
        lines.append(f"constexpr unsigned char k{name.capitalize()}Png[] = {{")
        for offset in range(0, len(data), 24):
            chunk = data[offset:offset + 24]
            lines.append("    " + ",".join(str(b) for b in chunk) + ",")
        lines.append("};")
        lines.append(f"constexpr MenuGlyphRecord k{name.capitalize()}Glyphs[] = {{")
        for code, ax, ay, w, h, left, top, advance in atlas["glyphs"]:
            lines.append(f"    {{{code}, {ax}, {ay}, {w}, {h}, {left}, {top}, {advance:.3f}F}},")
        lines.append("};")
    lines.append("} // namespace")
    lines.append("")
    for atlas in atlases:
        name = atlas["style"]
        cap = name.capitalize()
        lines.append(f"const MenuFontAtlasRecord k{cap}Atlas{{")
        lines.append(f"    {{k{cap}Png, sizeof(k{cap}Png)}}, {atlas['width']}U, {atlas['height']}U,")
        lines.append(f"    {PIXEL_SIZE}.0F, {atlas['ascent']}.0F, {atlas['descent']}.0F,")
        lines.append(f"    {{k{cap}Glyphs, sizeof(k{cap}Glyphs) / sizeof(k{cap}Glyphs[0])}}}};")
    lines.append("} // namespace Oot3dNativeGame::MenuFontData")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=HERE.parent / "oot3d_menu_font_atlas_data.cpp")
    args = parser.parse_args()
    atlases = [bake(style, file) for style, file in STYLES]
    emit(atlases, args.out)
    for atlas in atlases:
        print(f"{atlas['style']}: {len(atlas['glyphs'])} glyphs, {atlas['width']}x{atlas['height']}, "
              f"{len(atlas['png'])} PNG bytes")


if __name__ == "__main__":
    main()
