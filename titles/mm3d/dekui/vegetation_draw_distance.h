inline U32 Instruction(U32 pc,U32 word) {
    for(unsigned i=0;i<Hooks.size();++i) {
        const auto& h=Hooks[i];
        if((pc==h.pc&&word==h.code[2])||(pc==h.stock_pc&&word==h.stock_code[2]))
            return 0xef000000|FirstSVC+i;
    }
    return word;
}
template<class M> bool CodeMatches(M& m,U32 pc) {
    for(const auto& h:Hooks) {
        if(pc!=h.pc&&pc!=h.stock_pc)continue;
        const bool stock=pc==h.stock_pc;
        const auto& code=stock?h.stock_code:h.code;
        for(unsigned j=0;j<code.size();++j)
            if(m.Read(pc-8+4*j)!=std::optional<U32>(code[j]))return false;
        if(h.distance!=0.f&&h.shift_base==980.f) {
            // Verify the literal pool as well as the load/comparison sites.
            constexpr std::array<U32,11> pool{0x43480000,0x44960000,0x496a7900,0x44938000,0x40233333,0x49c80000,0x3b808081,0x3dcccccd,0x00000000,0x498e6200,0xb6560780};
            const U32 at=0x43704c; // Original EUR v1.1 pool
            for(unsigned j=0;j<pool.size();++j)
                if(m.Read(at+4*j)!=std::optional<U32>(pool[j]))return false;
        }
        if(h.distance!=0.f) {
            const U32 word=code[2];
            const U32 displacement=h.floating?(word&255)*4:word&4095;
            const U32 literal=pc+8+((word&(1u<<23))?displacement:0u-displacement);
            const float native=h.squared?h.distance*h.distance:h.distance;
            U32 bits=std::bit_cast<U32>(native);
            if(h.negate)bits=0u-bits;
            if(m.Read(literal)!=std::optional<U32>(bits))return false;
        }
        return true;
    }
    return false;
}
inline U32 Threshold(const Hook& h,float factor) {
    const float distance=h.distance+h.shift_base*(ActorDrawDistance::Clamp(factor)-1.f);
    const U32 bits=std::bit_cast<U32>(h.squared?distance*distance:distance);
    return h.negate?0u-bits:bits;
}
template<class M,class Registers,class Floats>
void Load(M& m,unsigned index,Registers& regs,Floats& floats,float factor) {
    if(index>=Hooks.size())return;
    const auto& h=Hooks[index];
    U32 value;
    if(h.distance!=0.f) {
        value=Threshold(h,factor);
    } else {
        // Displaced VLDR S1,[R1]. Default and excluded types replay exactly.
        const auto original=m.Read(regs[1]);
        if(!original)return;
        value=*original;
        const auto actor=m.Read(regs[4]);
        const auto params=m.Read(regs[4]+0x1c);
        if(actor&&(*actor&0x00ffffff)==0x6007f&&params&&(*params&3)<3) {
            factor=ActorDrawDistance::Clamp(factor);
            // Squared radii require up to 9x; the slider itself remains 1..3x.
            if(factor>1.f) {
                const float radius_squared=std::bit_cast<float>(*original);
                const float extended=radius_squared*factor*factor;
                value=std::isfinite(radius_squared)&&radius_squared>0.f&&std::isfinite(extended)
                    ?std::bit_cast<U32>(extended):*original;
            }
        }
    }
    if(h.floating)floats[h.reg]=value;else regs[h.reg]=value;
}
