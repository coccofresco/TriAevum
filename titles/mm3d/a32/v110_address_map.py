#!/usr/bin/env python3
"""Generate titles/mm3d/dekui/v110_address.h from an instruction correspondence.

mm3d-dekui and Project Restoration name addresses of the v1.0-derived image
Restoration's v1.1 patch installs. Their native code is the vanilla v1.1 code
shifted by a constant within long contiguous stretches (inserted or removed
code between them). The input lists contiguous word correspondences
(reference a + 4*i -> v1.1 b + 4*i), matched with branch displacements,
PC-relative loads, ADR offsets and literal pools masked; this keeps the
stretches of equal shift that follow each other (gaps of unmatched words
included) and writes them as a constexpr table.

    v110_address_map.py --correspondence instruction_correspondence.json \
        --output titles/mm3d/dekui/v110_address.h

Only code is translated: the data segment and BSS keep their addresses
(verified for every global the donors use), rodata and Restoration's
appended code have no translation. Every translated site is still guarded by
its v1.1 code words at run time.
"""

import argparse
import json
import sys
from pathlib import Path

HEADER = """// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by titles/mm3d/a32/v110_address_map.py; do not edit.
// Addresses of the v1.0-derived image Project Restoration installs (which
// mm3d-dekui and Restoration name) translated to the vanilla v1.1 code.bin.
#pragma once

#include <array>
#include <cstdint>

namespace Mm3dDekui {{

struct V110Shift {{
    std::uint32_t Begin; // reference address, inclusive
    std::uint32_t End;   // exclusive
    std::int32_t Delta;  // v1.1 = reference + Delta
}};

// {count} stretches covering {words} matched instructions of the reference
// text (0x00100000..0x0061D000).
inline constexpr std::array<V110Shift, {count}> kV110Shifts{{{{
{rows}
}}}};

inline constexpr std::uint32_t kTextEnd = 0x0061D000U;
inline constexpr std::uint32_t kDataBegin = 0x0064B000U;
inline constexpr std::uint32_t kRestorationCode = 0x007CF000U;

// The v1.1 address of a reference address, or 0 where there is none (an
// unmatched stretch of code, rodata, Restoration's appended code).
constexpr std::uint32_t V110(std::uint32_t reference) {{
    if (reference >= kDataBegin && reference < kRestorationCode) {{
        return reference;
    }}
    if (reference >= kTextEnd) {{
        return 0;
    }}
    std::size_t low = 0;
    std::size_t high = kV110Shifts.size();
    while (low < high) {{
        const std::size_t middle = low + (high - low) / 2;
        if (kV110Shifts[middle].End <= reference) {{
            low = middle + 1;
        }} else {{
            high = middle;
        }}
    }}
    if (low == kV110Shifts.size() || reference < kV110Shifts[low].Begin) {{
        return 0;
    }}
    return static_cast<std::uint32_t>(static_cast<std::int64_t>(reference) +
                                      kV110Shifts[low].Delta);
}}

// An A32 B/BL/BLX(imm) word at a reference address, re-encoded for the
// translated instruction so it still reaches the translated target.
constexpr std::uint32_t V110Branch(std::uint32_t word, std::uint32_t reference) {{
    std::int32_t offset = static_cast<std::int32_t>(word & 0x00FFFFFFU);
    if ((offset & 0x00800000) != 0) {{
        offset -= 0x01000000;
    }}
    const std::uint32_t target =
        V110(static_cast<std::uint32_t>(static_cast<std::int64_t>(reference) + 8 + 4 * offset));
    const std::uint32_t at = V110(reference);
    const std::int32_t translated =
        (static_cast<std::int32_t>(target) - static_cast<std::int32_t>(at) - 8) / 4;
    return (word & 0xFF000000U) | (static_cast<std::uint32_t>(translated) & 0x00FFFFFFU);
}}

}} // namespace Mm3dDekui
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--correspondence", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    ranges = json.loads(args.correspondence.read_text(encoding="utf-8"))["ranges"]
    spans = sorted(
        (int(r["restoration"], 16), int(r["restoration"], 16) + 4 * int(r["words"]),
         int(r["v110"], 16) - int(r["restoration"], 16))
        for r in ranges
    )
    merged = []
    for begin, end, delta in spans:
        if merged and begin < merged[-1][1]:
            print(f"overlapping correspondence at 0x{begin:08X}", file=sys.stderr)
            return 1
        if merged and merged[-1][2] == delta:
            merged[-1][1] = end
        else:
            merged.append([begin, end, delta])
    rows = "\n".join(f"    {{0x{b:08X}U, 0x{e:08X}U, {d}}}," for b, e, d in merged)
    words = sum(end - begin for begin, end, _ in spans) // 4
    args.output.write_text(
        HEADER.format(count=len(merged), words=words, rows=rows), encoding="utf-8", newline="\n")
    print(f"{len(merged)} stretches, {words} words")
    return 0


if __name__ == "__main__":
    sys.exit(main())
